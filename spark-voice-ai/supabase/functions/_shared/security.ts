// Segurança do webhook e rate limit básico (seção 3.4 / Etapa 1).
// - Secret do webhook é comparado por hash (SHA-256), nunca em claro.
// - Rate limit simples em memória por location (best-effort na edge).

/** SHA-256 hex de uma string (para comparar com webhook_secrets.secret_hash). */
export async function sha256Hex(input: string): Promise<string> {
  const data = new TextEncoder().encode(input);
  const digest = await crypto.subtle.digest('SHA-256', data);
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, '0')).join('');
}

/** Comparação constante-no-tempo entre dois hex de mesmo tamanho. */
export function timingSafeEqual(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let out = 0;
  for (let i = 0; i < a.length; i++) out |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return out === 0;
}

// Rate limit em memória (best-effort — a instância da edge é efêmera).
const buckets = new Map<string, { count: number; resetAt: number }>();

export function rateLimit(key: string, limit: number, windowMs: number): boolean {
  const now = Date.now();
  const b = buckets.get(key);
  if (!b || now > b.resetAt) {
    buckets.set(key, { count: 1, resetAt: now + windowMs });
    return true;
  }
  if (b.count >= limit) return false;
  b.count++;
  return true;
}
